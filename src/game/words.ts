/**
 * Случайное слово нужной длины. Исключаем слова, которые являются
 * префиксом другого активного слова (или наоборот), чтобы ввод не путался.
 */
export function randomWord(minLen: number, maxLen: number, activeWords: string[]): string {
  const inRange = WORDS.filter((word) => word.length >= minLen && word.length <= maxLen);
  const candidates = inRange.filter(
    (word) => !activeWords.some((active) => word.startsWith(active) || active.startsWith(word)),
  );
  const pool = candidates.length > 0 ? candidates : inRange.length > 0 ? inRange : WORDS;
  return pool[Math.floor(Math.random() * pool.length)];
}